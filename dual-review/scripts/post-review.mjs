#!/usr/bin/env node
// dual-review — post anchored findings as line comments in one GitHub COMMENT review, submitted or
// left pending. The review body carries the summary and any findings that could not be anchored.
//
//   post-review.mjs <cacheDir> [--submit]
//
// Uses the REST API only: a Claude Code cloud session blocks GitHub GraphQL.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { POSTED_MARKER } from "./findings.mjs";

const argv = process.argv.slice(2);
const cacheDir = argv[0] && !argv[0].startsWith("-") ? path.resolve(argv[0]) : null;
const submit = argv.includes("--submit");
if (!cacheDir) {
  console.error("usage: post-review.mjs <cacheDir> [--submit]");
  process.exit(2);
}

const meta = JSON.parse(fs.readFileSync(path.join(cacheDir, "meta.json"), "utf8"));
if (meta.mode !== "pr") {
  console.error("dual-review: posting requires a PR review (mode is not 'pr').");
  process.exit(1);
}
const data = JSON.parse(fs.readFileSync(meta.paths.findings, "utf8"));

function gh(args, input) {
  try {
    return execFileSync("gh", args, {
      cwd: meta.repoRoot,
      input,
      encoding: "utf8",
      stdio: [input === undefined ? "ignore" : "pipe", "pipe", "pipe"],
    }).trim();
  } catch (error) {
    const stdout = String(error.stdout ?? "").trim();
    let detail = String(error.stderr ?? "").trim() || error.message;
    try {
      const parsed = JSON.parse(stdout);
      const messages = [parsed.message, ...(parsed.errors ?? []).map((e) => (typeof e === "string" ? e : e.message))];
      detail = messages.filter(Boolean).join("; ") || detail;
    } catch {}
    throw new Error(detail);
  }
}

const reviewsPath = `repos/${meta.repo}/pulls/${meta.prNumber}/reviews`;

function createReview({ comments, body, event }) {
  const payload = { commit_id: meta.headSha, body, comments, ...(event ? { event } : {}) };
  return JSON.parse(gh(["api", "-X", "POST", reviewsPath, "--input", "-"], JSON.stringify(payload)));
}

function deleteReview(id) {
  gh(["api", "-X", "DELETE", `${reviewsPath}/${id}`]);
}

const footer = `_Generated by dual-review — Claude + ${meta.gptModel}._\n${POSTED_MARKER}`;

function lineCommentBody(finding) {
  const lines = [`**${finding.severity}: ${finding.title}**`];
  if (finding.impact) lines.push("", `Impact: ${finding.impact}`);
  if (finding.recommendation) lines.push("", `Recommendation: ${finding.recommendation}`);
  lines.push("", footer);
  return lines.join("\n");
}

function reviewComment(finding) {
  return {
    path: finding.file,
    line: finding.line,
    side: "RIGHT",
    ...(finding.startLine === null ? {} : { start_line: finding.startLine, start_side: "RIGHT" }),
    body: lineCommentBody(finding),
  };
}

function reviewBody(unanchored) {
  const visible = data.findings.filter((f) => f.bucket !== "already-raised");
  const sev = data.counts.severity;
  const lines = [
    "## Dual review summary",
    "",
    `Findings: ${visible.length} (blocker ${sev.blocker}, major ${sev.major}, minor ${sev.minor}, nit ${sev.nit})`,
  ];
  if (data.summary) lines.push("", data.summary);
  if (visible.length > 0) {
    lines.push("", "### Findings", "");
    for (const f of visible) lines.push(`- **${f.severity}: ${f.title}**${f.source !== "unknown" ? ` _(${f.source})_` : ""}`);
  }
  if (unanchored.length > 0) {
    lines.push("", "### Findings not anchored to the diff", "", "No line comment could be attached to these findings.");
    for (const f of unanchored) {
      lines.push("", `- **${f.severity}: ${f.title}**`);
      if (f.location && f.location.toLowerCase() !== "n/a") lines.push(`  - Location: \`${f.location}\``);
      if (f.impact) lines.push(`  - Impact: ${f.impact}`);
      if (f.recommendation) lines.push(`  - Recommendation: ${f.recommendation}`);
    }
  }
  lines.push("", footer);
  return lines.join("\n");
}

const lineComments = data.findings.filter((f) => f.bucket === "line");
const unanchored = data.findings.filter((f) => f.bucket === "unanchored");
const skipped = data.findings.filter((f) => f.bucket === "already-raised");

if (lineComments.length === 0 && unanchored.length === 0) {
  console.log(`Nothing to post${skipped.length ? ` (${skipped.length} already raised)` : ""}.`);
  process.exit(0);
}

// GitHub allows one pending review per person on a PR, and REST cannot add comments to it.
const reviews = JSON.parse(gh(["api", reviewsPath, "--paginate", "--slurp"]) || "[]").flat();
const existing = reviews.find((review) => review.state === "PENDING");
if (existing) {
  console.error(
    `dual-review: you have a pending review on PR #${meta.prNumber} (${existing.html_url}). Submit or delete it on GitHub, then post again.`,
  );
  process.exit(1);
}

// GitHub rejects the whole review when one comment is not on a diff line. After a rejection, try
// each comment alone in a pending review that is deleted at once, and keep the ones it accepts.
function acceptedComments(candidates) {
  const accepted = [];
  const rejected = [];
  for (const candidate of candidates) {
    try {
      deleteReview(createReview({ comments: [candidate.comment], body: "" }).id);
      accepted.push(candidate);
    } catch (error) {
      rejected.push(candidate.finding);
      console.error(`Failed to post ${candidate.finding.file}:${candidate.finding.line}: ${error.message}`);
    }
  }
  return { accepted, rejected };
}

let candidates = lineComments.map((finding) => ({ finding, comment: reviewComment(finding) }));
let failed = 0;
let review = null;
const event = submit ? "COMMENT" : undefined;

function post() {
  try {
    return createReview({ comments: candidates.map((c) => c.comment), body: reviewBody(unanchored), event });
  } catch (error) {
    if (candidates.length === 0) throw error;
    console.error(`GitHub rejected the review (${error.message}); checking each line comment.`);
  }
  const { accepted, rejected } = acceptedComments(candidates);
  candidates = accepted;
  failed = rejected.length;
  if (candidates.length === 0 && !submit) return null;
  // The review body carries the rejected findings, so none is lost.
  return createReview({ comments: candidates.map((c) => c.comment), body: reviewBody([...unanchored, ...rejected]), event });
}

if (candidates.length > 0 || submit) {
  try {
    review = post();
  } catch (error) {
    console.error(`dual-review: GitHub did not accept the review: ${error.message}`);
    process.exit(1);
  }
}

const posted = review ? candidates.length : 0;
if (review) for (const { finding } of candidates) console.log(`Posted ${finding.file}:${finding.line}`);
console.log(`Posted ${posted} line comment(s), ${failed} failed, ${skipped.length} skipped as already raised.`);

let state = "pending";
const reviewUrl = review?.html_url ?? null;
if (submit) {
  state = review ? "submitted" : "nothing-to-submit";
  console.log(review ? `Submitted comment review${reviewUrl ? `: ${reviewUrl}` : "."}` : "No comments were posted; nothing to submit.");
} else if (posted > 0) {
  console.log(`Left the review pending on PR #${meta.prNumber}; submit it from GitHub when ready.`);
} else {
  state = "nothing-posted";
  console.log("No comments were posted; no pending review was created.");
}

fs.writeFileSync(
  meta.paths.postResult,
  JSON.stringify({ at: new Date().toISOString(), posted, failed, skipped: skipped.length, unanchored: unanchored.length, state, reviewUrl }, null, 2),
);
